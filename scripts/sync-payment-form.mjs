/**
 * Pulls the live Tweeble payment-form definition and commits it as a snapshot
 * at src/data/payment-form.json.
 *
 *   npm run sync:payment-form
 *
 * The site renders its own payment UI, but it needs Tweeble's field ids, the
 * minimum amount and the submit URL to post a valid submission. Taking a
 * snapshot rather than fetching at build time keeps builds offline, fast and
 * deterministic.
 *
 * Re-run this whenever the form is edited in Tweeble - especially if fields are
 * added, removed or renamed, since the field ids change with them.
 */
import fs from 'node:fs';
import path from 'node:path';

const FORM_URL =
  process.env.TWEEBLE_PAYMENT_FORM_URL ??
  'https://www.tweeble.com/api/public/97c3ca18-82e4-4e1a-900a-f91339eefb81/payment-forms/34a99e7a-16f5-45b9-ac6c-c14086098cb6';

const OUT = path.join('src', 'data', 'payment-form.json');

const response = await fetch(FORM_URL, { headers: { Accept: 'application/json' } });
if (!response.ok) {
  console.error(`Failed to fetch the payment form: HTTP ${response.status}`);
  process.exit(1);
}

const form = await response.json();

// Sanity-check the shape before overwriting a working snapshot.
const problems = [];
if (!form.id) problems.push('missing id');
if (!form.submitUrl) problems.push('missing submitUrl');
if (!Array.isArray(form.fields) || form.fields.length === 0) problems.push('missing fields');
if (problems.length) {
  console.error('The response does not look like a payment form definition: ' + problems.join(', '));
  process.exit(1);
}

const snapshot = {
  _comment:
    'Generated by scripts/sync-payment-form.mjs. Do not edit by hand - re-run `npm run sync:payment-form` after changing the form in Tweeble.',
  _fetchedAt: new Date().toISOString(),
  ...form,
};

fs.writeFileSync(OUT, JSON.stringify(snapshot, null, 2) + '\n');

console.log(`Wrote ${OUT}`);
console.log(`  form         : ${form.name}`);
console.log(`  pricing      : ${form.pricingMode}${form.minimumAmountCents ? ` (min ${(form.minimumAmountCents / 100).toFixed(2)})` : ''}`);
console.log(`  submit       : ${form.submitUrl}`);
console.log('  fields       :');
for (const field of form.fields) {
  console.log(`    ${field.id}  ${field.required ? '*' : ' '} ${field.type.padEnd(9)} ${field.label}`);
}
