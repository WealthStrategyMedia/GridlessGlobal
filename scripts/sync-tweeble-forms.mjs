/**
 * Pulls the live Tweeble form definitions and commits them as snapshots under
 * src/data/.
 *
 *   npm run sync:forms
 *
 * The site renders its own UI for these forms, but it needs Tweeble's field
 * ids, required flags, option lists and submit URLs to post a valid
 * submission. Taking a snapshot rather than fetching at build time keeps builds
 * offline, fast and deterministic.
 *
 * Re-run this whenever a form is edited in Tweeble - especially if fields are
 * added, removed or renamed, since the field ids change with them.
 */
import fs from 'node:fs';
import path from 'node:path';

const ACCOUNT = process.env.TWEEBLE_ACCOUNT_ID ?? '97c3ca18-82e4-4e1a-900a-f91339eefb81';
const base = `https://www.tweeble.com/api/public/${ACCOUNT}`;

const FORMS = [
  {
    name: 'payment form',
    url: process.env.TWEEBLE_PAYMENT_FORM_URL ?? `${base}/payment-forms/34a99e7a-16f5-45b9-ac6c-c14086098cb6`,
    out: path.join('src', 'data', 'payment-form.json'),
  },
  {
    name: 'contact form',
    url: process.env.TWEEBLE_CONTACT_FORM_URL ?? `${base}/contact-forms/4ac109dd-175e-4cf9-8ce9-f6e524176115`,
    out: path.join('src', 'data', 'contact-form.json'),
  },
  {
    name: 'newsletter form',
    url: process.env.TWEEBLE_NEWSLETTER_FORM_URL ?? `${base}/contact-forms/80d3e890-cc12-46d5-8285-e4900b4683a7`,
    out: path.join('src', 'data', 'newsletter-form.json'),
  },
];

let failed = false;

for (const form of FORMS) {
  process.stdout.write(`Fetching ${form.name}... `);
  let definition;
  try {
    const response = await fetch(form.url, { headers: { Accept: 'application/json' } });
    if (!response.ok) throw new Error(`HTTP ${response.status}`);
    definition = await response.json();
  } catch (error) {
    console.log('FAILED');
    console.error(`  ${error.message}`);
    console.error(`  Leaving the existing snapshot at ${form.out} untouched.`);
    failed = true;
    continue;
  }

  // Sanity-check the shape before overwriting a working snapshot.
  const problems = [];
  if (!definition.id) problems.push('missing id');
  if (!definition.submitUrl) problems.push('missing submitUrl');
  if (!Array.isArray(definition.fields) || definition.fields.length === 0) problems.push('missing fields');
  if (problems.length) {
    console.log('FAILED');
    console.error(`  Response does not look like a form definition: ${problems.join(', ')}`);
    failed = true;
    continue;
  }

  fs.writeFileSync(
    form.out,
    JSON.stringify(
      {
        _comment:
          'Generated by scripts/sync-tweeble-forms.mjs. Do not edit by hand - re-run `npm run sync:forms` after changing the form in Tweeble.',
        _fetchedAt: new Date().toISOString(),
        ...definition,
      },
      null,
      2
    ) + '\n'
  );

  console.log('ok');
  console.log(`  name    : ${definition.name}`);
  console.log(`  submit  : ${definition.submitUrl}`);
  console.log(`  written : ${form.out}`);
  for (const field of definition.fields) {
    console.log(`     ${field.id}  ${field.required ? '*' : ' '} ${String(field.type).padEnd(9)} ${field.label}`);
  }
  console.log('');
}

if (failed) process.exit(1);
